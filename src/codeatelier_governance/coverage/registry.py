"""In-memory wrapper registry with a best-effort Postgres mirror.

This module is the core abstraction for F9. Every SDK process that wraps
an LLM client registers itself here; ``GovernanceSDK.start()`` drains
the in-memory registry into Postgres so compliance reports generated by
peer replicas can see this process's wrappers.

Security / invariants:

* Registration is fire-and-forget. A failed INSERT logs at WARN and
  returns normally. The in-memory registry is unaffected.
* Raw hostnames are NEVER written. ``hostname_hash`` is
  ``HMAC-SHA256(workspace_salt, hostname)`` — PII-safe under GDPR
  Art. 4(1).
* The Postgres schema has a trigger (see the F9 migration) that rejects
  INSERTs for any ``agent_id`` not present in ``governance_policies``.
  This closes the rogue-process spoofing vector: only governed
  identities can appear in the registry.
"""
from __future__ import annotations

import hashlib
import hmac
import socket
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any

import structlog

logger = structlog.get_logger(__name__)


@dataclass
class WrapperRegistration:
    """One row in the wrapper registry."""

    agent_id: str
    provider: str  # "openai" | "anthropic" | ...
    hostname_hash: str
    instance_id: uuid.UUID
    sdk_version: str | None = None
    registered_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )
    last_seen_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )


def _resolve_workspace_salt() -> bytes:
    """Return a stable per-deployment salt for hostname hashing.

    Prefers ``GOVERNANCE_WORKSPACE_SALT``; falls back to the audit secret
    if set. As a last resort, derives a deterministic salt from the
    hostname so hashes in a single process are at least self-consistent.
    The fallback is logged so operators see when PII protection is
    degraded to "no-op pepper."
    """
    import os

    salt = os.environ.get("GOVERNANCE_WORKSPACE_SALT")
    if salt:
        return salt.encode("utf-8")
    audit = os.environ.get("GOVERNANCE_AUDIT_SECRET")
    if audit:
        return audit.encode("utf-8")
    logger.warning(
        "coverage.registry.workspace_salt_missing",
        detail=(
            "Neither GOVERNANCE_WORKSPACE_SALT nor GOVERNANCE_AUDIT_SECRET "
            "set. Falling back to a process-local salt for hostname "
            "hashing. Registrations from this process will not align "
            "with peer replicas."
        ),
    )
    return b"governance-workspace-salt-fallback"


def compute_hostname_hash(hostname: str, *, salt: bytes | None = None) -> str:
    """HMAC-SHA256 of hostname keyed by the workspace salt.

    Pure function: deterministic for ``(salt, hostname)``. Exposed for
    tests that need to reproduce the hash outside the registry.
    """
    key = salt if salt is not None else _resolve_workspace_salt()
    return hmac.new(key, hostname.encode("utf-8"), hashlib.sha256).hexdigest()


class WrapperRegistry:
    """Per-SDK in-memory registry with a Postgres mirror.

    The registry is keyed by ``(agent_id, provider, instance_id)`` — the
    same composite used as the UNIQUE constraint in the DDL. ``instance_id``
    is a random UUID generated once per :class:`WrapperRegistry` instance
    and is stable for the lifetime of the SDK process. PIDs are explicitly
    NOT used because they get recycled.
    """

    def __init__(self, *, salt: bytes | None = None) -> None:
        self._registrations: dict[
            tuple[str, str, uuid.UUID], WrapperRegistration
        ] = {}
        self._instance_id = uuid.uuid4()
        self._salt = salt if salt is not None else _resolve_workspace_salt()
        try:
            self._hostname_hash = compute_hostname_hash(
                socket.gethostname(), salt=self._salt,
            )
        except Exception:  # noqa: BLE001
            self._hostname_hash = compute_hostname_hash(
                "unknown", salt=self._salt,
            )

    @property
    def instance_id(self) -> uuid.UUID:
        return self._instance_id

    @property
    def hostname_hash(self) -> str:
        return self._hostname_hash

    def register(
        self,
        agent_id: str,
        provider: str,
        *,
        sdk_version: str | None = None,
    ) -> WrapperRegistration:
        """Record an in-memory registration. Never raises."""
        reg = WrapperRegistration(
            agent_id=agent_id,
            provider=provider,
            hostname_hash=self._hostname_hash,
            instance_id=self._instance_id,
            sdk_version=sdk_version,
        )
        key = (agent_id, provider, self._instance_id)
        existing = self._registrations.get(key)
        if existing is not None:
            existing.last_seen_at = datetime.now(timezone.utc)
            return existing
        self._registrations[key] = reg
        return reg

    def snapshot(self) -> list[WrapperRegistration]:
        """Return a shallow copy of current registrations."""
        return list(self._registrations.values())

    async def flush_to_postgres(self, engine: Any) -> None:
        """Best-effort UPSERT of all in-memory rows into Postgres.

        Also runs the opportunistic 30-day prune (LIMIT 100) inline.
        Any exception is logged at WARN and swallowed — invariant #1.
        """
        if engine is None or not self._registrations:
            # Still attempt the prune if engine is available.
            if engine is not None:
                await self._prune_opportunistic(engine)
            return
        try:
            from sqlalchemy import text

            rows = [
                {
                    "agent_id": r.agent_id,
                    "provider": r.provider,
                    "hostname_hash": r.hostname_hash,
                    "instance_id": str(r.instance_id),
                    "sdk_version": r.sdk_version,
                }
                for r in self._registrations.values()
            ]
            async with engine.begin() as conn:
                for row in rows:
                    try:
                        await conn.execute(
                            text(
                                "INSERT INTO governance_wrapper_registrations "
                                "(agent_id, provider, hostname_hash, "
                                "instance_id, sdk_version, registered_at, "
                                "last_seen_at) "
                                "VALUES (:agent_id, :provider, :hostname_hash, "
                                ":instance_id, :sdk_version, NOW(), NOW()) "
                                "ON CONFLICT (agent_id, provider, instance_id) "
                                "DO UPDATE SET last_seen_at = NOW()"
                            ),
                            row,
                        )
                    except Exception as exc:  # noqa: BLE001
                        # FK/trigger rejection for an unknown agent is
                        # expected (rogue-process prevention). Log and
                        # keep going — one bad row must not block the
                        # rest of the flush.
                        logger.warning(
                            "coverage.registry.row_insert_failed",
                            agent_id=row["agent_id"],
                            provider=row["provider"],
                            error_type=type(exc).__name__,
                        )
        except Exception as exc:  # noqa: BLE001
            logger.warning(
                "coverage.registry.flush_failed",
                error_type=type(exc).__name__,
                detail="Wrapper registry flush failed; in-memory state unaffected.",
            )
            return

        await self._prune_opportunistic(engine)

    async def _prune_opportunistic(self, engine: Any) -> None:
        """Delete up to 100 rows older than 30 days. Best-effort."""
        try:
            from sqlalchemy import text

            async with engine.begin() as conn:
                await conn.execute(
                    text(
                        "DELETE FROM governance_wrapper_registrations "
                        "WHERE ctid IN ("
                        "  SELECT ctid FROM governance_wrapper_registrations "
                        "  WHERE last_seen_at < NOW() - INTERVAL '30 days' "
                        "  LIMIT 100"
                        ")"
                    )
                )
        except Exception as exc:  # noqa: BLE001
            logger.warning(
                "coverage.registry.prune_failed",
                error_type=type(exc).__name__,
            )
